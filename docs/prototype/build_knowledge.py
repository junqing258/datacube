"""Bundle repository Markdown as a read-only snapshot for the local prototype."""
import json
import re
from pathlib import Path

from markdown_it import MarkdownIt

PROTOTYPE = Path(__file__).resolve().parent
SOURCE = PROTOTYPE.parent / "knowledge"
OUTPUT = PROTOTYPE / "knowledge-data.js"


def main():
    markdown = MarkdownIt("commonmark", {"html": False}).enable("table")
    documents = {}
    for path in sorted(SOURCE.glob("*/*.md")):
        topic = path.parent.name
        version = path.stem
        if not re.fullmatch(r"[a-z][a-z0-9-]*", topic) or not re.fullmatch(r"v[1-9][0-9]*", version):
            raise SystemExit(f"知识文件路径应为 knowledge/<topic>/v<N>.md：{path.relative_to(SOURCE)}")

        tokens = markdown.parse(path.read_text(encoding="utf-8"))
        if not tokens or tokens[0].tag != "h1" or tokens[0].type != "heading_open":
            raise SystemExit(f"首段应为一级标题：{path}")
        body = tokens[3:]
        if not body or body[0].type != "paragraph_open":
            raise SystemExit(f"标题下应有一段主题摘要：{path}")

        documents.setdefault(topic, {})[version] = {
            "title": tokens[1].content,
            "summary": body[1].content,
            "source": path.relative_to(PROTOTYPE.parent).as_posix(),
            "html": markdown.renderer.render(body, markdown.options, {}),
        }

    if not documents:
        raise SystemExit(f"未找到 Markdown 知识文件：{SOURCE}")

    bundle = json.dumps(documents, ensure_ascii=False, indent=2)
    OUTPUT.write_text(
        "// Generated by build_knowledge.py from ../knowledge.\n"
        f"const knowledgeDocuments = {bundle};\n",
        encoding="utf-8",
    )
    print(f"生成 {sum(len(versions) for versions in documents.values())} 份只读知识文档 → {OUTPUT.name}")


if __name__ == "__main__":
    main()
